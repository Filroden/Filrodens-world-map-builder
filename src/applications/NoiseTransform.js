/**
 * The Standard engine's noise frame: where the map sits in the infinite noise field (the pan
 * offsets) and how large the noise is drawn (the elevation scale). Panning or rescaling the noise
 * moves the terrain under everything placed on the map, so everything placed on it is carried
 * along: pins, labels, decorations, brush strokes, regions and routes.
 *
 * A change of frame from one set of parameters to another is a uniform scale about the noise
 * origin followed by a shift, and the same two parameter sets describe the way back, which is what
 * lets an undo step restore the terrain along with everything on it (see VectorHistory's noise
 * entry). The brush strokes are moved here, since they belong to the terrain rather than to the
 * vector state; the vector state is covered by its own snapshot, and the mesh content by
 * MeshIntegration.transformContent.
 */
export class NoiseTransform {
    /** The noise frame the map has now. */
    static current(app) {
        return {
            offsetX: app.uiState["noise.offsetX"] || 0,
            offsetY: app.uiState["noise.offsetY"] || 0,
            scale: app.uiState["noise.elevation.scale"],
        };
    }

    /**
     * The point transforms between two noise frames. A point on the terrain at (x, y) under the
     * `from` frame is found at toTarget(x, y) under the `to` frame: the terrain scales about the
     * noise origin by the ratio of the two scales, and shifts by the change of offset.
     * @param {{offsetX: number, offsetY: number, scale: number}} from
     * @param {{offsetX: number, offsetY: number, scale: number}} to
     * @returns {{ratio: number, toTarget: function(number, number): number[], toSource: function(number, number): number[]}}
     */
    static between(from, to) {
        const ratio = to.scale / from.scale;
        return {
            ratio,
            toTarget: (x, y) => [(x + from.offsetX) * ratio - to.offsetX, (y + from.offsetY) * ratio - to.offsetY],
            toSource: (x, y) => [(x + to.offsetX) / ratio - from.offsetX, (y + to.offsetY) / ratio - from.offsetY],
        };
    }

    /**
     * Puts the map into a noise frame: the brush strokes (undone ones included) move from the
     * current frame to the new one and are built again from scratch, and the frame is written to
     * the UI state. The terrain itself is regenerated by the caller.
     * @param {object} app
     * @param {{offsetX: number, offsetY: number, scale: number}} frame
     */
    static apply(app, frame) {
        const { ratio, toTarget } = this.between(this.current(app), frame);
        if (app.brushEngine) {
            const moveStroke = (stroke) => {
                for (const point of stroke.points) [point.x, point.y] = toTarget(point.x, point.y);
                stroke.size *= ratio;
            };
            app.brushEngine.history.forEach(moveStroke);
            app.brushEngine.redoStack.forEach(moveStroke);
            // The brushed layer was built from the strokes where they were
            app.brushEngine.invalidateLayerCache();
        }
        app.uiState["noise.offsetX"] = frame.offsetX;
        app.uiState["noise.offsetY"] = frame.offsetY;
        app.uiState["noise.elevation.scale"] = frame.scale;
    }
}
