// Writes a tutorial page's two texts from its step file: the wiki page (the reader's steps with
// their screenshots) and the video's shooting script (per step, the narration, what happens on
// screen, the camera and how long to hold). Both come from the same steps, so the wiki, the
// checkpoints and the videos cannot disagree.
import { describeActions } from "./actions.mjs";

/** Where the checkpoints are downloaded from, for the wiki's "Start from" links. */
const RAW_SAMPLES = "https://github.com/Filroden/Filrodens-world-map-builder/raw/main/samples/tutorial";

/** How many pages the tutorial has when complete (the pages are written one batch at a time). */
const TUTORIAL_LENGTH = 10;

/** Seconds the video holds after a step that does not say. */
const DEFAULT_PAUSE = 2;

/** "01-new-world": a page's file stem, used for its checkpoint, script and screenshots. */
export function pageStem(page) {
    return `${String(page.number).padStart(2, "0")}-${page.slug}`;
}

/** The wiki page's name ("Tutorial 1 A new world") and its file ("Tutorial-1-A-new-world.md"). */
export function wikiName(page) {
    return `Tutorial ${page.number} ${page.title}`;
}

export function wikiFile(page) {
    return `${wikiName(page).replaceAll(" ", "-")}.md`;
}

/** A screenshot's file name. */
export function shotFile(page, shot) {
    return `${pageStem(page)}-${shot.name}.png`;
}

/** Indents every line of a block (for text and images inside a numbered step). */
function indent(text, by) {
    return text
        .split("\n")
        .map((line) => (line ? by + line : line))
        .join("\n");
}

function startFrom(page, pages) {
    if (!page.start) return page.startText ?? "Nothing: this page makes the map.";
    const before = pages.find((other) => pageStem(other) === page.start);
    const file = `${page.start}.json`;
    const own = before ? ` Or carry on with your own map from [[${wikiName(before)}]].` : "";
    return `[${file}](${RAW_SAMPLES}/${file}), the map as it is at the end of ${before ? `[[${wikiName(before)}]]` : "the page before"}. Download it, then open **Maps** on the rail and click **Import JSON**; the map is listed under its name, and **Load** opens it.${own}`;
}

/**
 * The wiki page.
 *
 * @param {object} page - The step file's page.
 * @param {object[]} pages - Every page, in order (for the links before and after).
 * @param {string} source - The step file's path, named in the page's note to editors.
 * @returns {string}
 */
export function wikiMarkdown(page, pages, source) {
    const index = pages.indexOf(page);
    const next = pages[index + 1];
    const lines = [];
    lines.push(`<!-- Generated by npm run tutorial:build from ${source}. Edit the step file, not this page. -->`);
    lines.push("", `> Part of the tutorial: page ${page.number} of ${Math.max(TUTORIAL_LENGTH, pages.length)}`, "");
    lines.push(`# Tutorial ${page.number}: ${page.title}`, "");
    lines.push(page.goal, "");
    lines.push(`**Start from:** ${startFrom(page, pages)}`, "");
    if (page.intro) lines.push(page.intro.trim(), "");
    lines.push("## Steps", "");
    let number = 0;
    for (const step of page.steps) {
        if (!step.instruction) continue;
        number += 1;
        const body = [step.instruction.trim()];
        if (step.screenshot) {
            const caption = step.caption ?? step.screenshot.alt ?? "";
            body.push("", `![${caption}](images/tutorial/${shotFile(page, step.screenshot)})`);
            if (step.caption) body.push("", step.caption);
        }
        if (step.note) body.push("", step.note.trim());
        const marker = `${number}. `;
        lines.push(`${marker}${indent(body.join("\n"), " ".repeat(marker.length)).trimStart()}`, "");
    }
    for (const [heading, text] of [
        ["What you should see", page.whatYouSee],
        ["In Foundry", page.foundry],
        ["On your own map", page.onYourOwn],
    ]) {
        if (text) lines.push(`## ${heading}`, "", text.trim(), "");
    }
    if (next) lines.push(`**Next:** [[${wikiName(next)}]]`, "");
    if (page.related?.length) lines.push(`**Related:** ${page.related.map((name) => `[[${name}]]`).join(", ")}`, "");
    return `${lines.join("\n").trimEnd()}\n`;
}

/** The video's shooting script for a page. */
export function videoScript(page, source) {
    const lines = [];
    lines.push(`<!-- Generated by npm run tutorial:script from ${source}. Edit the step file, not this script. -->`, "");
    lines.push(`# Video script: tutorial ${page.number}, ${page.title}`, "");
    lines.push(`**Goal:** ${page.goal}`, "");
    if (page.narration) lines.push(`**Opening narration:** ${page.narration.trim()}`, "");
    let total = 0;
    let number = 0;
    for (const step of page.steps) {
        const onScreen = describeActions(step);
        const narration = step.narration ?? step.instruction;
        if (!narration && !onScreen.length) continue;
        number += 1;
        const pause = step.pause ?? DEFAULT_PAUSE;
        total += pause;
        lines.push(`## ${number}. ${step.title ?? step.id}`, "");
        if (narration) lines.push(`**Narration:** ${narration.trim().replaceAll("\n", " ")}`, "");
        if (onScreen.length) lines.push("**On screen:**", "", ...onScreen.map((text) => `- ${text}`), "");
        lines.push(`**Camera:** ${describeCamera(step)}`, "");
        lines.push(`**Hold:** ${pause} s after the action`, "");
        if (step.screenshot) lines.push(`**Matches the wiki's image:** \`${shotFile(page, step.screenshot)}\``, "");
    }
    lines.push(`---`, "", `${number} steps; at least ${total} s of holds, plus the actions themselves.`, "");
    return lines.join("\n");
}

function describeCamera(step) {
    const camera = step.camera ?? step.screenshot?.region ?? "studio";
    if (typeof camera === "string") return camera === "studio" ? "the whole studio" : `the ${camera}`;
    if (camera.selector || camera.union) return "a close-up of the part of the studio in the wiki's image";
    if (camera.map) return `the map from ${camera.map[0]}, ${camera.map[1]} to ${camera.map[2]}, ${camera.map[3]}`;
    if (camera.zoom) return `zoom ${camera.zoom} on ${camera.centre?.join(", ") ?? "the centre"}`;
    return camera.text ?? JSON.stringify(camera);
}
